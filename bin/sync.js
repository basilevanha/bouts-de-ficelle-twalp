#!/usr/bin/env node

/**
 * Sync script
 *
 * Copies source files from src/ into the WordPress theme directory (THEME_DIR).
 * In dev mode, also watches for changes and re-syncs.
 *
 * Usage:
 *   node bin/sync.js              # Initial sync only
 *   node bin/sync.js --watch      # Sync + watch for changes
 *   node bin/sync.js --production # Sync + copy vendor/ for deployment
 */

import { cpSync, mkdirSync, writeFileSync, existsSync, lstatSync, unlinkSync } from 'fs';
import { resolve, dirname, relative, join, sep } from 'path';
import { config } from 'dotenv';
import { fileURLToPath } from 'url';
import { compilePo, compileAllPo } from './compile-po.js';
import { buildSprite } from './build-sprite.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT = resolve(__dirname, '..');

config({ path: resolve(ROOT, '.env') });

const THEME_DIR = resolve(ROOT, process.env.THEME_DIR || './public/wp-content/themes/wp-twalp');
const isProduction = process.argv.includes('--production');
const isWatch = process.argv.includes('--watch');

console.log(`[sync] Theme directory: ${THEME_DIR}`);

/**
 * Ensure a directory exists.
 */
function ensureDir(dir) {
  mkdirSync(dir, { recursive: true });
}

/**
 * Copy a directory recursively.
 */
function copyDir(src, dest) {
  ensureDir(dest);
  cpSync(src, dest, { recursive: true, force: true });
}

/**
 * Create the autoload-path.php file that points to the repo root's vendor/.
 * Uses VENDOR_PATH env var if set (e.g. /var/www/vendor for Docker),
 * otherwise falls back to the local repo path.
 */
function writeAutoloadPath() {
  const vendorPath = process.env.VENDOR_PATH
    ? `${process.env.VENDOR_PATH}/autoload.php`
    : resolve(ROOT, 'vendor/autoload.php');
  const safeVendorPath = vendorPath.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  const content = `<?php\n// Auto-generated by sync.js — do not edit\nreturn '${safeVendorPath}';\n`;
  writeFileSync(resolve(THEME_DIR, 'autoload-path.php'), content);
  console.log('[sync] Generated autoload-path.php');
}

/**
 * Prepare src/acf-json/ so Docker can bind-mount it into the theme.
 *
 * Docker bind-mounts `src/acf-json/` over `theme/acf-json/` inside the
 * container — the source directory must exist on the host before the
 * container starts, otherwise Docker creates it as root. Also removes
 * any legacy symlink or stray directory at the theme destination left
 * over from previous sync versions, so the bind mount has a clean
 * target on the next container start.
 */
function prepareAcfJsonDir() {
  const src = resolve(ROOT, 'src/acf-json');
  const dest = resolve(THEME_DIR, 'acf-json');

  ensureDir(src);

  try {
    const stat = lstatSync(dest);
    if (stat.isSymbolicLink()) {
      unlinkSync(dest);
      console.log('[sync] Removed legacy acf-json symlink');
    }
  } catch {
    // Doesn't exist, fine — Docker will create the mount point
  }
}

/**
 * Prepare src/theme/languages/ so Docker can bind-mount it into the theme.
 *
 * Same rationale as prepareAcfJsonDir: the host directory must exist before
 * the container starts, otherwise Docker creates it as root. Also removes
 * any legacy symlink at the theme destination.
 */
function prepareLanguagesDir() {
  const src = resolve(ROOT, 'src/theme/languages');
  const dest = resolve(THEME_DIR, 'languages');

  ensureDir(src);

  try {
    const stat = lstatSync(dest);
    if (stat.isSymbolicLink()) {
      unlinkSync(dest);
      console.log('[sync] Removed legacy languages symlink');
    }
  } catch {
    // Doesn't exist, fine — Docker will create the mount point
  }
}

/**
 * Write the "hot" file for Vite dev server detection.
 */
function writeHotFile() {
  const distDir = resolve(THEME_DIR, 'dist');
  ensureDir(distDir);
  const devServer = process.env.VITE_DEV_SERVER || 'http://localhost:5173';
  writeFileSync(resolve(distDir, 'hot'), devServer);
  console.log('[sync] Created dist/hot file');
}

/**
 * Remove the "hot" file.
 */
function removeHotFile() {
  const hotFile = resolve(THEME_DIR, 'dist/hot');
  try {
    unlinkSync(hotFile);
  } catch {
    // File doesn't exist
  }
}

/**
 * Main sync operation.
 */
function sync() {
  ensureDir(THEME_DIR);

  // Copy PHP theme files (excluding languages/ — bind-mounted in dev,
  // copied explicitly in prod below, to avoid a recursive-into-source loop).
  const themeSrc = resolve(ROOT, 'src/theme');
  ensureDir(THEME_DIR);
  cpSync(themeSrc, THEME_DIR, {
    recursive: true,
    force: true,
    filter: (src) => {
      const rel = relative(themeSrc, src);
      return rel !== 'languages' && !rel.startsWith('languages' + sep);
    },
  });
  console.log('[sync] Copied src/theme/ → theme (excluding languages/)');

  // Copy Twig templates
  copyDir(resolve(ROOT, 'src/views'), resolve(THEME_DIR, 'views'));
  console.log('[sync] Copied src/views/ → theme/views/');

  // Copy static assets
  if (existsSync(resolve(ROOT, 'src/fonts'))) {
    copyDir(resolve(ROOT, 'src/fonts'), resolve(THEME_DIR, 'assets/fonts'));
  }
  if (existsSync(resolve(ROOT, 'src/images'))) {
    copyDir(resolve(ROOT, 'src/images'), resolve(THEME_DIR, 'assets/images'));
  }

  // Build the SVG sprite from src/icons/*.svg → theme/assets/icons/sprite.svg
  const spriteCount = buildSprite(
    resolve(ROOT, 'src/icons'),
    resolve(THEME_DIR, 'assets/icons/sprite.svg'),
  );
  if (spriteCount > 0) {
    console.log(`[sync] Built SVG sprite with ${spriteCount} icon(s)`);
  }

  // Generate autoload-path.php (points to repo root vendor/)
  if (!isProduction) {
    writeAutoloadPath();
  }

  // In dev, Docker bind-mounts src/acf-json → theme/acf-json.
  // In prod, no container runs — copy files into the theme instead.
  if (!isProduction) {
    prepareAcfJsonDir();
    prepareLanguagesDir();
    writeHotFile();
  } else {
    if (existsSync(resolve(ROOT, 'src/acf-json'))) {
      const acfDest = resolve(THEME_DIR, 'acf-json');
      try {
        const stat = lstatSync(acfDest);
        if (stat.isSymbolicLink()) {
          unlinkSync(acfDest);
        }
      } catch {
        // Doesn't exist yet, fine
      }
      copyDir(resolve(ROOT, 'src/acf-json'), acfDest);
    }
    if (existsSync(resolve(ROOT, 'src/theme/languages'))) {
      // Recompile every .mo from its .po so a deployed theme always ships
      // up-to-date translations, even if a .po was last edited by hand
      // outside a running dev watcher.
      const langSrc = resolve(ROOT, 'src/theme/languages');
      const compiled = compileAllPo(langSrc);
      if (compiled > 0) {
        console.log(`[sync] Compiled ${compiled} .po file(s) → .mo`);
      }
      const langDest = resolve(THEME_DIR, 'languages');
      try {
        const stat = lstatSync(langDest);
        if (stat.isSymbolicLink()) {
          unlinkSync(langDest);
        }
      } catch {
        // Doesn't exist yet, fine
      }
      copyDir(langSrc, langDest);
    }
    // Copy vendor/ into theme for deployment
    if (existsSync(resolve(ROOT, 'vendor'))) {
      copyDir(resolve(ROOT, 'vendor'), resolve(THEME_DIR, 'vendor'));
      console.log('[sync] Copied vendor/ → theme/vendor/');
    }
    // A dev run leaves autoload-path.php pointing to the Docker vendor path
    // (/var/www/vendor), which doesn't exist on the production server:
    // remove it so functions.php falls back to the bundled vendor/.
    try {
      unlinkSync(resolve(THEME_DIR, 'autoload-path.php'));
      console.log('[sync] Removed dev autoload-path.php');
    } catch {
      // Not there, fine
    }
    removeHotFile();
  }

  console.log('[sync] Done!');
}

/**
 * Watch mode: re-sync on file changes.
 */
async function watch() {
  const { watch: chokidarWatch } = await import('chokidar');

  const languagesDir = resolve(ROOT, 'src/theme/languages');
  const iconsDir = resolve(ROOT, 'src/icons');

  const watcher = chokidarWatch([
    resolve(ROOT, 'src/theme'),
    resolve(ROOT, 'src/views'),
    resolve(ROOT, 'src/fonts'),
    resolve(ROOT, 'src/images'),
    resolve(ROOT, 'src/icons'),
  ], {
    ignoreInitial: true,
    awaitWriteFinish: { stabilityThreshold: 100 },
  });

  watcher.on('all', (event, filePath) => {
    const rel = relative(resolve(ROOT, 'src'), filePath);
    console.log(`[sync] ${event}: ${rel}`);

    if (filePath === languagesDir || filePath.startsWith(languagesDir + sep)) {
      // src/theme/languages/ is bind-mounted from the container, so files
      // here must NOT be copied — that would write into their own source.
      // But a changed .po still needs its .mo recompiled in place: WordPress
      // only reads the .mo, and the bind mount makes it visible immediately.
      if (filePath.endsWith('.po') && (event === 'add' || event === 'change')) {
        if (compilePo(filePath)) {
          console.log(`[i18n] Recompiled ${relative(languagesDir, filePath)} → .mo`);
        }
      }
      return;
    }

    if (filePath === iconsDir || filePath.startsWith(iconsDir + sep)) {
      // Any change under src/icons/ rebuilds the whole sprite — symbol ids
      // depend on the full set of files, so a per-file copy isn't enough.
      const count = buildSprite(iconsDir, resolve(THEME_DIR, 'assets/icons/sprite.svg'));
      console.log(`[sprite] Rebuilt sprite with ${count} icon(s)`);
      return;
    }

    if (filePath.startsWith(resolve(ROOT, 'src/theme'))) {
      const dest = resolve(THEME_DIR, relative(resolve(ROOT, 'src/theme'), filePath));
      ensureDir(dirname(dest));
      try { cpSync(filePath, dest, { force: true }); } catch (err) { console.error(`[sync] Failed to copy ${rel}:`, err.message); }
    } else if (filePath.startsWith(resolve(ROOT, 'src/views'))) {
      const dest = resolve(THEME_DIR, 'views', relative(resolve(ROOT, 'src/views'), filePath));
      ensureDir(dirname(dest));
      try { cpSync(filePath, dest, { force: true }); } catch (err) { console.error(`[sync] Failed to copy ${rel}:`, err.message); }
    } else if (filePath.startsWith(resolve(ROOT, 'src/fonts'))) {
      const dest = resolve(THEME_DIR, 'assets/fonts', relative(resolve(ROOT, 'src/fonts'), filePath));
      ensureDir(dirname(dest));
      try { cpSync(filePath, dest, { force: true }); } catch (err) { console.error(`[sync] Failed to copy ${rel}:`, err.message); }
    } else if (filePath.startsWith(resolve(ROOT, 'src/images'))) {
      const dest = resolve(THEME_DIR, 'assets/images', relative(resolve(ROOT, 'src/images'), filePath));
      ensureDir(dirname(dest));
      try { cpSync(filePath, dest, { force: true }); } catch (err) { console.error(`[sync] Failed to copy ${rel}:`, err.message); }
    }
  });

  console.log('[sync] Watching for changes...');
}

// Run
sync();
if (isWatch) {
  await watch();
}
